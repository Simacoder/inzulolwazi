/**
 * Build the browser extension's data file from the curated corpus.
 *
 * The extension flags loaded terms and topics on web pages, so the words it looks for and the notes it shows
 * both come from content/glossary.json, content/claims.json and content/sources.json. Nothing is written from
 * memory here: this script only selects and copies. Run `node scripts/build-extension.mjs --check` to fail when
 * extension/data is out of date.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (/** @type {string} */ file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));

/** Aliases that are ordinary words on their own. Flagging them would mark pages that have nothing to do with the term. */
export const GENERIC_ALIASES = ['classification', 'Zimbabwe', 'house in stone', 'the house in stone'];
/** Extra search phrases for a glossary term. Each must be a plain phrase for the term itself. */
export const EXTRA_MATCHERS = { term_hamitic_theory: ['Hamitic'], term_colonial_classification: ['colonial classification'] };
/** Claims that add topics the glossary does not cover. Each phrase must be built from that claim's own keywords. */
export const CLAIM_MATCHERS = {
  claim_giza_builders: ['Giza'],
  claim_counting_bones: ['Lebombo', 'Ishango'],
  claim_african_centred_history: ['Chancellor Williams'],
};
/** The claim page that best explains a glossary term, when there is one. */
export const RELATED_CLAIM = {
  term_bantu: 'claim_bantu_language_history',
  term_khoisan: 'claim_khoisan_term',
  term_great_zimbabwe_name: 'claim_great_zimbabwe_trade',
};
const TYPE_LABELS = {
  scholarship: 'Peer-reviewed scholarship', archaeology: 'Archaeology', genetics: 'Genetics', linguistics: 'Linguistics',
  colonial_record: 'Colonial record', critical_commentary: 'Critical or interpretive commentary', oral_testimony: 'Oral testimony',
};

/** @param {{ id: string, title: string, authors: string[], year: number, sourceType: keyof typeof TYPE_LABELS, url: string }} source */
function sourceLine(source) {
  const author = source.authors.length > 2 ? `${source.authors[0]} et al.` : source.authors.join(' and ');
  return { label: `${author} (${source.year}), ${source.title}`, type: TYPE_LABELS[source.sourceType] ?? source.sourceType, url: source.url };
}

/** @param {string[]} values */
const unique = (values) => [...new Set(values)];

export function buildIndex() {
  const glossary = read('content/glossary.json');
  const claims = read('content/claims.json');
  const claimList = Array.isArray(claims) ? claims : claims.claims;
  const sourceFile = read('content/sources.json');
  const sourceList = Array.isArray(sourceFile) ? sourceFile : sourceFile.sources;
  const sources = new Map(sourceList.map((/** @type {{ id: string }} */ source) => [source.id, source]));
  const claimById = new Map(claimList.map((/** @type {{ id: string }} */ claim) => [claim.id, claim]));
  const linesFor = (/** @type {string[]} */ ids) => ids.map((id) => sources.get(id)).filter(Boolean).map(sourceLine);

  const entries = [];
  for (const term of glossary) {
    const related = claimById.get(RELATED_CLAIM[/** @type {keyof typeof RELATED_CLAIM} */ (term.id)] ?? '');
    const phrases = unique([term.term, ...term.aliases, ...(EXTRA_MATCHERS[/** @type {keyof typeof EXTRA_MATCHERS} */ (term.id)] ?? [])])
      .filter((phrase) => !GENERIC_ALIASES.includes(phrase));
    entries.push({
      id: term.id, kind: 'term', label: term.term, matchers: phrases,
      summary: term.definition.en, framing: term.framing.en, sources: linesFor(term.sourceIds),
      appPath: related ? `#/claim/${related.id}` : `#/glossary?q=${encodeURIComponent(term.term)}`,
      relatedLabel: related ? related.topic : null,
    });
  }
  for (const [claimId, phrases] of Object.entries(CLAIM_MATCHERS)) {
    const claim = claimById.get(claimId);
    if (!claim) throw new Error(`Unknown claim ${claimId}`);
    entries.push({
      id: claim.id, kind: 'claim', label: claim.topic, matchers: phrases, status: claim.status,
      summary: claim.statement.en, framing: claim.rationale.en, sources: linesFor(claim.sourceIds),
      appPath: `#/claim/${claim.id}`, relatedLabel: null,
    });
  }
  return { version: 1, entries };
}

const out = path.join(root, 'extension/data');
const render = () => {
  const index = buildIndex();
  return { json: `${JSON.stringify(index, null, 2)}\n`, js: `/* Generated by scripts/build-extension.mjs from content/*.json. Do not edit. */\nglobalThis.INZ_DATA = ${JSON.stringify(index)};\n` };
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render();
  if (process.argv.includes('--check')) {
    const same = existsSync(`${out}/index.json`) && readFileSync(`${out}/index.json`, 'utf8') === next.json && readFileSync(`${out}/index.js`, 'utf8') === next.js;
    if (!same) { console.error('extension/data is out of date. Run: npm run build:extension'); process.exit(1); }
    console.log('extension/data is up to date');
  } else {
    writeFileSync(`${out}/index.json`, next.json);
    writeFileSync(`${out}/index.js`, next.js);
    console.log(`Wrote extension/data (${JSON.parse(next.json).entries.length} entries)`);
  }
}
